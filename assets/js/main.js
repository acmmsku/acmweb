function applyLanguage(lang) {
  document.documentElement.lang = lang;
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.tr;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = dict[key];
    if (value === undefined) return;
    if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    const value = dict[key];
    if (value !== undefined) el.setAttribute('aria-label', value);
  });

  const titleKey = document.body.getAttribute('data-title-key') || 'meta.title';
  if (dict[titleKey]) document.title = dict[titleKey];

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
  });

  localStorage.setItem('acm-lang', lang);
}

// Marks the correct top-level nav link active for the current page/hash.
// Works across separate HTML pages (each page only has its own sections),
// so this replaces per-section scroll observation with simple page+hash matching.
function setActiveNavLink(navLinks) {
  const currentPage = location.pathname.split('/').pop() || 'index.html';
  let currentHash = location.hash;
  if (currentPage === 'index.html' && !currentHash) currentHash = '#anasayfa';

  navLinks.forEach(link => {
    const [hrefPage, hrefHash] = link.getAttribute('href').split('#');
    const page = hrefPage || currentPage;
    const active = page === currentPage && (!hrefHash || ('#' + hrefHash) === currentHash);
    link.classList.toggle('is-active', active);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const nav = document.getElementById('siteNav');
  const navToggle = document.getElementById('navToggle');
  const navMenu = document.getElementById('navMenu');
  const navLinks = document.querySelectorAll('.nav-link');

  // Language toggle
  const savedLang = localStorage.getItem('acm-lang');
  const initialLang = savedLang === 'en' ? 'en' : 'tr';
  applyLanguage(initialLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLanguage(btn.getAttribute('data-lang')));
  });

  // Navbar background on scroll
  const onScroll = () => {
    nav.classList.toggle('is-scrolled', window.scrollY > 20);
  };
  onScroll();
  window.addEventListener('scroll', onScroll, { passive: true });

  // Mobile nav toggle
  navToggle.addEventListener('click', () => {
    const isOpen = navMenu.classList.toggle('is-open');
    navToggle.setAttribute('aria-expanded', String(isOpen));
    document.body.style.overflow = isOpen ? 'hidden' : '';
  });

  navMenu.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      if (window.innerWidth <= 720) {
        navMenu.classList.remove('is-open');
        navToggle.setAttribute('aria-expanded', 'false');
        document.body.style.overflow = '';
      }
    });
  });

  // Active nav link (page + hash based, works across separate pages)
  setActiveNavLink(navLinks);
  window.addEventListener('hashchange', () => setActiveNavLink(navLinks));

  // Scroll reveal animation
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  document.querySelectorAll('[data-reveal]').forEach(el => revealObserver.observe(el));

  // Footer year
  const yearEl = document.getElementById('year');
  if (yearEl) yearEl.textContent = new Date().getFullYear();
});
